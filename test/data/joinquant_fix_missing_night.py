def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    if not MISSING_RANGES:
        print("[提示] MISSING_RANGES 为空, 请先把 find_missing_night_days.py 输出的列表粘贴进来。")
        return

    frames = []
    for td, start, end in MISSING_RANGES:
        print(f">>> 拉取交易日 {td}: {start} ~ {end} ...")
        try:
            df = get_price(FUTURE_CODE, start_date=start, end_date=end,
                           frequency=FREQ, fields=FIELDS)
        except Exception as e:
            print(f"    [失败] {type(e).__name__}: {e}")
            continue
        if df is None or df.empty:
            print(f"    [警告] 该时段无数据")
            continue
        df = df.reset_index()
        # 兼容聚宽 get_price 返回 单层(time) 或 双层(time, code) 索引
        df = df.rename(columns={df.columns[0]: "datetime"})
        if "code" not in df.columns:
            df.insert(1, "code", FUTURE_CODE)   # 单层索引时补上常量 code
        df["datetime"] = pd.to_datetime(df["datetime"]).astype(str)
        # 缺失的字段补 NaN, 保证列完整
        for f in FIELDS:
            if f not in df.columns:
                df[f] = float("nan")
        # 只保留需要的列
        df = df[["datetime", "code"] + FIELDS]
        print(f"    得到 {len(df)} 根 bar ({df['datetime'].min()} ~ {df['datetime'].max()})")
        frames.append(df)

    if not frames:
        print("未拉到任何数据。")
        return

    out = pd.concat(frames, ignore_index=True)
    out = out.drop_duplicates(subset=["datetime", "code"], keep="last").sort_values("datetime")

    # merge 换月字段(用聚宽 get_dominant_future 计算)
    root = _root_from_code(FUTURE_CODE)
    out["_dt"] = pd.to_datetime(out["datetime"])
    day_mask = out["_dt"].dt.hour < 20
    trade_days = sorted(pd.unique(out.loc[day_mask, "_dt"].dt.normalize()))
    out = out.drop(columns=["_dt"])
    sched = build_dominant_schedule(root, trade_days)
    if not sched.empty:
        out["datetime"] = pd.to_datetime(out["datetime"])
        out["td"] = assign_trading_day_local(out["datetime"], sched["td"])
        out = out.merge(sched, on="td", how="left")
        # schedule 未覆盖的交易日(主力获取失败被跳过)会留空, 沿用相邻值并告警
        missing_td = sorted(pd.unique(out.loc[out["symbol"].isna(), "td"]))
        if len(missing_td) > 0:
            shown = [pd.Timestamp(t).date().isoformat() for t in missing_td[:5]]
            print(f"    [警告] {len(missing_td)} 个交易日主力获取失败, 换月字段沿用相邻值: {shown}...")
        for c in ["symbol", "weighted_factor", "cur_weighted_factor"]:
            if c in out.columns:
                out[c] = out[c].ffill().bfill()
        out["symbol"] = out["symbol"].fillna("")
        out["weighted_factor"] = out["weighted_factor"].fillna(1.0)
        out["cur_weighted_factor"] = out["cur_weighted_factor"].fillna(1.0)
        out["is_rollover"] = out["is_rollover"].fillna(False).astype(bool)
        out = out.drop(columns=["td"], errors="ignore")
    else:
        print("[警告] get_dominant_future 返回空, CSV 不含换月字段")

    path = f"{OUT_DIR}/{FUTURE_CODE}_fix_night.csv"
    out.to_csv(path, index=False)
    print(f"\n完成: 共 {len(out)} 行 -> {path}")
    print("请下载该 CSV, 然后本地导入:")
    print("  python -u test/data/import_c0_1min_to_db.py --csv <下载的CSV路径>")


if __name__ == "__main__":
    main()
